  /* ---- the rules ----
     Pure: a board, some tiles you want to put on it, and a verdict. No state, no
     DOM, no network. That is what lets the host judge a play for real and every
     other window judge the same play as a preview while it's being laid out,
     from exactly the same code — two implementations of "is this a word and
     what's it worth" would drift apart within a week.

     It does NOT check the tiles are in your rack; only the host holds racks. */

  function scrAt(board, r, c){
    if(r<0 || c<0 || r>=SCR_SIZE || c>=SCR_SIZE) return null;
    return board[r*SCR_SIZE+c];
  }

  /** The whole word running through (r,c) in one direction, with its squares. */
  function scrRun(board, r, c, dr, dc){
    let sr = r, sc = c;
    while(scrAt(board, sr-dr, sc-dc)){ sr -= dr; sc -= dc; }
    const out = [];
    while(scrAt(board, sr, sc)){ out.push({r:sr, c:sc, t:scrAt(board, sr, sc)}); sr += dr; sc += dc; }
    return out;
  }

  function scrScoreRun(run, fresh){
    let sum = 0, mult = 1;
    for(const sq of run){
      const isNew = fresh.some(f=>f.r===sq.r && f.c===sq.c);
      let v = sq.t.blank ? 0 : (SCR_VALUES[sq.t.ch] || 0);
      if(isNew){
        const p = scrPrem(sq.r, sq.c);
        if(p === 'd') v *= 2;
        else if(p === 't') v *= 3;
        else if(p === 'D' || p === '*') mult *= 2;
        else if(p === 'T') mult *= 3;
      }
      sum += v;
    }
    return sum * mult;
  }

  /* Reasons that mean "you aren't finished yet" rather than "that's wrong".
     The live preview stays quiet for these — nagging somebody about gaps while
     they're still reaching for the next tile is just noise. */
  const SCR_UNFINISHED = {'One line at a time.':1, 'Leave no gaps.':1,
                          'A word needs two letters.':1, 'Nothing to play.':1,
                          'The first word needs two letters.':1};
  function scrUnfinished(why){ return !!SCR_UNFINISHED[why]; }

  /** {ok:true, pts, words} or {why}. Never mutates `board`. */
  function scrJudge(board, tiles){
    if(!tiles || !tiles.length) return {why:'Nothing to play.'};

    for(const t of tiles){
      if(!(t.r>=0 && t.r<SCR_SIZE && t.c>=0 && t.c<SCR_SIZE)) return {why:'Off the board.'};
      if(board[t.r*SCR_SIZE+t.c]) return {why:'That square is taken.'};
      if('abcdefghijklmnopqrstuvwxyz'.indexOf(t.ch) < 0) return {why:'That is not a letter.'};
    }
    for(let i=0;i<tiles.length;i++) for(let j=i+1;j<tiles.length;j++){
      if(tiles[i].r===tiles[j].r && tiles[i].c===tiles[j].c) return {why:'Two tiles on one square.'};
    }

    const rows = new Set(tiles.map(t=>t.r)), cols = new Set(tiles.map(t=>t.c));
    const single = tiles.length === 1;
    if(!single && rows.size > 1 && cols.size > 1) return {why:'One line at a time.'};

    // lay them down on a scratch copy
    const scratch = board.slice();
    for(const t of tiles) scratch[t.r*SCR_SIZE+t.c] = {ch:t.ch, blank:!!t.blank};

    // no gaps along the line the tiles were placed on
    if(!single){
      const horiz = rows.size === 1;
      const fixed = horiz ? tiles[0].r : tiles[0].c;
      const vals = tiles.map(t=>horiz ? t.c : t.r);
      for(let k=Math.min.apply(null,vals); k<=Math.max.apply(null,vals); k++){
        if(!scrAt(scratch, horiz?fixed:k, horiz?k:fixed)) return {why:'Leave no gaps.'};
      }
    }

    // first move covers the star; every later move touches something
    const first = board.every(x=>!x);
    if(first){
      if(tiles.length < 2) return {why:'The first word needs two letters.'};
      if(!tiles.some(t=>t.r===7 && t.c===7)) return {why:'The first word crosses the star.'};
    }else{
      const touches = tiles.some(t=>
        scrAt(board,t.r-1,t.c) || scrAt(board,t.r+1,t.c) ||
        scrAt(board,t.r,t.c-1) || scrAt(board,t.r,t.c+1));
      if(!touches) return {why:'Words have to join what is already there.'};
    }

    /* Every word this created: the line the tiles sit on, plus a crossing word
       wherever a new tile landed against an old one. Runs are keyed by first
       square and direction, so a tile extending a word its neighbour also
       extends isn't counted twice. */
    const runs = [], seen = {};
    const add = (r, c, dr, dc)=>{
      const run = scrRun(scratch, r, c, dr, dc);
      if(run.length < 2) return;
      const k = run[0].r+','+run[0].c+','+dr+','+dc;
      if(seen[k]) return;
      seen[k] = 1;
      runs.push(run);
    };
    if(single){
      add(tiles[0].r, tiles[0].c, 0, 1);
      add(tiles[0].r, tiles[0].c, 1, 0);
    }else{
      const horiz = rows.size === 1;
      add(tiles[0].r, tiles[0].c, horiz?0:1, horiz?1:0);            // the line itself
      for(const t of tiles) add(t.r, t.c, horiz?1:0, horiz?0:1);    // its crossings
    }
    if(!runs.length) return {why:'A word needs two letters.'};

    const words = runs.map(run=>run.map(sq=>sq.t.ch).join(''));
    const bad = words.filter(w=>!scrIsWord(w));
    if(bad.length){
      return {why:(bad.length > 1 ? 'Not words: ' : 'Not a word: ')
                  + bad.map(w=>w.toUpperCase()).join(', '), bad};
    }

    let pts = 0;
    for(const run of runs) pts += scrScoreRun(run, tiles);
    if(tiles.length === SCR_RACK) pts += SCR_BINGO;

    /* Two things worth telling the caller about, for the achievements.
       `sweep` is the whole rack down in one turn — the same condition the bingo
       bonus is paid on. `tens` is the most ten-point letters standing in any one
       word, blanks not counted: a blank playing as a Q scores nothing and is not
       the thing being celebrated. */
    let tens = 0;
    for(const run of runs){
      let n = 0;
      for(const sq of run) if(!sq.t.blank && SCR_VALUES[sq.t.ch] === 10) n++;
      if(n > tens) tens = n;
    }
    return {ok:true, pts, words, sweep: tiles.length === SCR_RACK, tens};
  }

